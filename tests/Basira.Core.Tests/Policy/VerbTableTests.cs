    [Fact]
    public void HarmlessNamesAreRecognized()
    {
        Assert.True(VerbTable.IsHarmlessName("Search"));
        Assert.True(VerbTable.IsHarmlessName("Sign in"));
        Assert.True(VerbTable.IsHarmlessName("التالي"));
        Assert.False(VerbTable.IsHarmlessName("Send"));
        Assert.False(VerbTable.IsHarmlessName(""));
    }

